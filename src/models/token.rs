use derive_more::Display;

#[derive(Debug, PartialEq, Clone, Display)]
pub enum Token {
    #[display("{_0}")]
    Ident(String),
    #[display("{_0}")]
    ConstInt(i32),
    #[display("{_0}l")]
    ConstLong(i64),
    #[display("{_0}u")]
    ConstUInt(u32),
    #[display("{_0}ul")]
    ConstULong(u64),
    #[display("int")]
    KwInt,
    #[display("long")]
    KwLong,
    #[display("signed")]
    KwSigned,
    #[display("unsigned")]
    KwUnsigned,
    #[display("void")]
    KwVoid,
    #[display("return")]
    KwReturn,
    #[display("if")]
    KwIf,
    #[display("else")]
    KwElse,
    #[display("goto")]
    KwGoto,
    #[display("do")]
    KwDo,
    #[display("while")]
    KwWhile,
    #[display("for")]
    KwFor,
    #[display("break")]
    KwBreak,
    #[display("continue")]
    KwContinue,
    #[display("switch")]
    KwSwitch,
    #[display("case")]
    KwCase,
    #[display("default")]
    KwDefault,
    #[display("static")]
    KwStatic,
    #[display("extern")]
    KwExtern,
    #[display("(")]
    LParen,
    #[display(")")]
    RParen,
    #[display("{{")]
    LBrace,
    #[display("}}")]
    RBrace,
    #[display(";")]
    Semicolon,
    #[display("+")]
    Plus,
    #[display("-")]
    Hyphen,
    #[display("*")]
    Star,
    #[display("/")]
    Slash,
    #[display("%")]
    Percent,
    #[display("|")]
    Tilde,
    #[display("&")]
    Ampersand,
    #[display("|")]
    VerticalBar,
    #[display("^")]
    Caret,
    #[display("<<")]
    LShift,
    #[display(">>")]
    RShift,
    #[display("!")]
    Bang,
    #[display("&&")]
    LogicalAnd,
    #[display("||")]
    LogicalOr,
    #[display("==")]
    DoubleEqual,
    #[display("!=")]
    BangEqual,
    #[display("<")]
    LessThan,
    #[display("<=")]
    LessOrEqual,
    #[display(">")]
    GreaterThan,
    #[display(">=")]
    GreaterOrEqual,
    #[display("=")]
    Equal,
    #[display("+=")]
    PlusEqual,
    #[display("-=")]
    HyphenEqual,
    #[display("*=")]
    StarEqual,
    #[display("/=")]
    SlashEqual,
    #[display("%=")]
    PercentEqual,
    #[display("&=")]
    AndEqual,
    #[display("|=")]
    VBarEqual,
    #[display("^=")]
    CaretEqual,
    #[display("<<=")]
    LShiftEqual,
    #[display(">>=")]
    RShiftEqual,
    #[display("++")]
    DoublePlus,
    #[display("--")]
    DoubleHyphen,
    #[display("?")]
    Question,
    #[display(":")]
    Colon,
    #[display(",")]
    Comma,
}
